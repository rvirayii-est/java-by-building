// Run with:  java -cp <path to the H2 jar> lessons/31-transactions/examples/AllOrNothing.java   (from the repository root)
// A sale does three things: take stock off the shelf, store the receipt, write the stock log. We make the third step
// fail ON PURPOSE and look at what is left, first with auto-commit (every statement saved at once), then in a transaction.
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

public class AllOrNothing {

    public static void main(String[] args) throws SQLException {
        try (Connection db = DriverManager.getConnection("jdbc:h2:mem:all-or-nothing")) {
            run(db, "CREATE TABLE product (name VARCHAR(40) PRIMARY KEY, quantity INT NOT NULL CHECK (quantity >= 0))");
            run(db, "CREATE TABLE sale (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product VARCHAR(40) NOT NULL, quantity INT NOT NULL)");
            // the stock log has a rule that our sale will break (a movement must be for at least 1 unit)
            run(db, "CREATE TABLE stock_log (product VARCHAR(40) NOT NULL, quantity INT NOT NULL CHECK (quantity > 0))");
            run(db, "INSERT INTO product VALUES ('Rice 25kg', 12)");

            System.out.println("== 1. AUTO-COMMIT (the default): each statement is saved the moment it runs");
            showState(db, "Before");
            try {
                sell(db, 5, 0); // the 0 breaks the stock_log rule in step 3
            } catch (SQLException e) {
                System.out.println("Step 3 failed (SQL state " + e.getSQLState() + ": a CHECK rule refused the log line)");
            }
            showState(db, "After ");
            System.out.println("The shelf lost 5 sacks and a receipt exists, but there is no log line. The shop's records disagree.\n");

            run(db, "UPDATE product SET quantity = 12 WHERE name = 'Rice 25kg'");
            run(db, "DELETE FROM sale");

            System.out.println("== 2. TRANSACTION: setAutoCommit(false) ... commit() or rollback()");
            showState(db, "Before");
            db.setAutoCommit(false);
            try {
                sell(db, 5, 0);
                db.commit();
            } catch (SQLException e) {
                System.out.println("Step 3 failed (SQL state " + e.getSQLState() + ": a CHECK rule refused the log line)");
                db.rollback();
                System.out.println("rollback() called");
            } finally {
                db.setAutoCommit(true);
            }
            showState(db, "After ");
            System.out.println("Nothing changed. The three steps happened together or not at all.\n");

            System.out.println("== 3. The same sale with a correct log line: commit() keeps everything");
            db.setAutoCommit(false);
            try {
                sell(db, 5, 5);
                db.commit();
            } finally {
                db.setAutoCommit(true);
            }
            showState(db, "After ");
        }
    }

    /** The three steps of a sale. logQuantity is what step 3 writes in the log (0 is a mistake the database refuses). */
    static void sell(Connection db, int quantity, int logQuantity) throws SQLException {
        run(db, "UPDATE product SET quantity = quantity - " + quantity + " WHERE name = 'Rice 25kg'"); // step 1
        run(db, "INSERT INTO sale (product, quantity) VALUES ('Rice 25kg', " + quantity + ")");        // step 2
        run(db, "INSERT INTO stock_log VALUES ('Rice 25kg', " + logQuantity + ")");                    // step 3
    }

    static void showState(Connection db, String label) throws SQLException {
        System.out.println(label + ": rice on shelf = " + one(db, "SELECT quantity FROM product")
                + ", receipts = " + one(db, "SELECT COUNT(*) FROM sale") + ", log lines = " + one(db, "SELECT COUNT(*) FROM stock_log"));
    }

    static String one(Connection db, String sql) throws SQLException {
        try (Statement statement = db.createStatement(); ResultSet rows = statement.executeQuery(sql)) {
            rows.next();
            return rows.getString(1);
        }
    }

    static void run(Connection db, String sql) throws SQLException {
        try (Statement statement = db.createStatement()) {
            statement.execute(sql);
        }
    }
}
