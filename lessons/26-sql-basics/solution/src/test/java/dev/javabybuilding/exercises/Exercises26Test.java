package dev.javabybuilding.exercises;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

class Exercises26Test {

    private Connection db;

    @BeforeEach
    void openDatabase() throws SQLException {
        db = DriverManager.getConnection("jdbc:h2:mem:l26-" + UUID.randomUUID());
        run("CREATE TABLE product (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60) NOT NULL UNIQUE,"
                + " price DECIMAL(10,2) NOT NULL, reorder_level INT NOT NULL, quantity INT NOT NULL)");
        run("INSERT INTO product (name, price, reorder_level, quantity) VALUES"
                + " ('Rice 25kg', 1250.50, 10, 17), ('Cooking Oil 1L', 98.00, 10, 12), ('Sugar 1kg', 75.00, 10, 4),"
                + " ('Sardines 155g', 24.00, 20, 30), ('Soy Sauce 500ml', 38.00, 5, 0), ('Instant Noodles', 14.00, 30, 5)");
    }

    @AfterEach
    void closeDatabase() throws SQLException {
        db.close();
    }

    private void run(String sql) throws SQLException {
        try (Statement statement = db.createStatement()) {
            statement.execute(sql);
        }
    }

    /** The rows of a query as lines of text: cells joined with "|". */
    private List<String> rows(String sql) throws SQLException {
        List<String> lines = new ArrayList<>();
        try (Statement statement = db.createStatement(); ResultSet rs = statement.executeQuery(sql)) {
            ResultSetMetaData meta = rs.getMetaData();
            while (rs.next()) {
                List<String> cells = new ArrayList<>();
                for (int c = 1; c <= meta.getColumnCount(); c++) {
                    cells.add(rs.getString(c));
                }
                lines.add(String.join("|", cells));
            }
        }
        return lines;
    }

    private String columnNames(String sql) throws SQLException {
        try (Statement statement = db.createStatement(); ResultSet rs = statement.executeQuery(sql)) {
            ResultSetMetaData meta = rs.getMetaData();
            List<String> names = new ArrayList<>();
            for (int c = 1; c <= meta.getColumnCount(); c++) {
                names.add(meta.getColumnLabel(c).toLowerCase());
            }
            return String.join(",", names);
        }
    }

    @Test
    void cheapProductsAreUnder100AndDearestFirst() throws SQLException {
        assertEquals("name,price", columnNames(SqlDrills.cheapProducts()));
        assertEquals(List.of("Cooking Oil 1L|98.00", "Sugar 1kg|75.00", "Soy Sauce 500ml|38.00", "Sardines 155g|24.00", "Instant Noodles|14.00"),
                rows(SqlDrills.cheapProducts()));
    }

    @Test
    void namesWithOilIgnoreCapitals() throws SQLException {
        run("INSERT INTO product (name, price, reorder_level, quantity) VALUES ('Olive OIL 500ml', 300.00, 2, 3)");
        assertEquals(List.of("Cooking Oil 1L", "Olive OIL 500ml"), rows(SqlDrills.namesWithOil()));
    }

    @Test
    void lowCountSkipsTheOutProducts() throws SQLException {
        assertEquals("low_count", columnNames(SqlDrills.lowCount()));
        assertEquals(List.of("2"), rows(SqlDrills.lowCount())); // Sugar (4) and Instant Noodles (5); Soy Sauce is OUT, not LOW
    }

    @Test
    void averagePriceIsTheMeanOfAllPrices() throws SQLException {
        assertEquals("average_price", columnNames(SqlDrills.averagePrice()));
        assertEquals("249.92", new java.math.BigDecimal(rows(SqlDrills.averagePrice()).get(0)).setScale(2, java.math.RoundingMode.HALF_UP).toPlainString());
    }

    @Test
    void threeDearestAreInOrder() throws SQLException {
        assertEquals(List.of("Rice 25kg|1250.50", "Cooking Oil 1L|98.00", "Sugar 1kg|75.00"), rows(SqlDrills.threeDearest()));
    }

    @Test
    void receivingSoySauceChangesOnlySoySauce() throws SQLException {
        run(SqlDrills.receiveSoySauce());
        assertEquals(List.of("Soy Sauce 500ml|10"), rows("SELECT name, quantity FROM product WHERE name LIKE 'Soy%'"));
        assertEquals(List.of("17"), rows("SELECT quantity FROM product WHERE name = 'Rice 25kg'"));
    }

    @Test
    void raiseCheapPricesTouchesOnlyProductsUnder50() throws SQLException {
        run(SqlDrills.raiseCheapPrices());
        assertEquals(List.of("Instant Noodles|15.40", "Rice 25kg|1250.50", "Sardines 155g|26.40", "Soy Sauce 500ml|41.80"),
                rows("SELECT name, price FROM product WHERE name IN ('Instant Noodles', 'Rice 25kg', 'Sardines 155g', 'Soy Sauce 500ml') ORDER BY name"));
    }

    @Test
    void addCoffeeAddsOneRowWithTheNextId() throws SQLException {
        run(SqlDrills.addCoffee());
        assertEquals(List.of("7|Coffee Sachet|8.50|50|0"), rows("SELECT * FROM product WHERE name = 'Coffee Sachet'"));
        assertEquals(List.of("7"), rows("SELECT COUNT(*) FROM product"));
    }

    @Test
    void removeOutOfStockDeletesOnlySoySauce() throws SQLException {
        run(SqlDrills.removeOutOfStock());
        assertEquals(List.of("5"), rows("SELECT COUNT(*) FROM product"));
        assertEquals(List.of(), rows("SELECT name FROM product WHERE name LIKE 'Soy%'"));
    }
}
