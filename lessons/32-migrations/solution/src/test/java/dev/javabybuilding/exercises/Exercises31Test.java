package dev.javabybuilding.exercises;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

class Exercises31Test {

    private String url;
    private Connection db;

    @BeforeEach
    void openDatabase() throws SQLException {
        url = "jdbc:h2:mem:l31-" + UUID.randomUUID();
        db = DriverManager.getConnection(url);
        try (Statement statement = db.createStatement()) {
            statement.execute("CREATE TABLE product (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60) NOT NULL UNIQUE,"
                    + " price DECIMAL(10,2) NOT NULL, reorder_level INT NOT NULL, quantity INT NOT NULL CHECK (quantity >= 0))");
            statement.execute("INSERT INTO product (name, price, reorder_level, quantity) VALUES"
                    + " ('Rice 25kg', 1250.50, 10, 17), ('Rice 1kg bag', 55.00, 10, 3)");
        }
    }

    @AfterEach
    void closeDatabase() throws SQLException {
        db.close();
    }

    /** Reads a quantity over a second connection, so only COMMITTED data is seen. */
    private int committedQuantity(String name) throws SQLException {
        try (Connection other = DriverManager.getConnection(url);
             Statement statement = other.createStatement();
             ResultSet rows = statement.executeQuery("SELECT quantity FROM product WHERE name = '" + name + "'")) {
            rows.next();
            return rows.getInt(1);
        }
    }

    // ---- inTransaction

    @Test
    void finishedWorkIsCommitted() throws SQLException {
        TransactionDrills.inTransaction(db, c -> c.createStatement().execute("UPDATE product SET quantity = 99 WHERE name = 'Rice 25kg'"));
        assertEquals(99, committedQuantity("Rice 25kg"));
    }

    @Test
    void failingWorkIsRolledBackAndTheSameExceptionIsThrown() throws SQLException {
        IllegalStateException boom = new IllegalStateException("boom");
        IllegalStateException caught = assertThrows(IllegalStateException.class, () -> TransactionDrills.inTransaction(db, c -> {
            c.createStatement().execute("UPDATE product SET quantity = 99 WHERE name = 'Rice 25kg'");
            throw boom;
        }));
        assertEquals(boom, caught);
        assertEquals(17, committedQuantity("Rice 25kg"));
    }

    @Test
    void anSqlErrorRollsBackTheEarlierStatementsToo() throws SQLException {
        assertThrows(SQLException.class, () -> TransactionDrills.inTransaction(db, c -> {
            c.createStatement().execute("UPDATE product SET quantity = 99 WHERE name = 'Rice 25kg'");
            c.createStatement().execute("UPDATE product SET quantity = -5 WHERE name = 'Rice 1kg bag'"); // the CHECK refuses
        }));
        assertEquals(17, committedQuantity("Rice 25kg"));
        assertEquals(3, committedQuantity("Rice 1kg bag"));
    }

    @Test
    void autoCommitIsBackOnAfterSuccessAndAfterFailure() throws SQLException {
        TransactionDrills.inTransaction(db, c -> {});
        assertTrue(db.getAutoCommit());
        assertThrows(IllegalStateException.class, () -> TransactionDrills.inTransaction(db, c -> {
            throw new IllegalStateException("boom");
        }));
        assertTrue(db.getAutoCommit());
    }

    // ---- moveStock

    @Test
    void moveStockTakesFromOneAndGivesToTheOther() throws SQLException {
        TransactionDrills.moveStock(db, "Rice 25kg", "Rice 1kg bag", 5);
        assertEquals(12, committedQuantity("Rice 25kg"));
        assertEquals(8, committedQuantity("Rice 1kg bag"));
    }

    @Test
    void moveStockRefusesWhenThereIsNotEnoughAndChangesNothing() throws SQLException {
        IllegalStateException e = assertThrows(IllegalStateException.class, () -> TransactionDrills.moveStock(db, "Rice 1kg bag", "Rice 25kg", 4));
        assertEquals("Not enough stock", e.getMessage());
        assertEquals(3, committedQuantity("Rice 1kg bag"));
        assertEquals(17, committedQuantity("Rice 25kg"));
    }

    @Test
    void moveStockToAnUnknownProductPutsTheStockBack() throws SQLException {
        IllegalStateException e = assertThrows(IllegalStateException.class, () -> TransactionDrills.moveStock(db, "Rice 25kg", "Ghost", 5));
        assertEquals("Unknown product", e.getMessage());
        assertEquals(17, committedQuantity("Rice 25kg")); // the first UPDATE had happened; the rollback undid it
    }

    @Test
    void moveStockFromAnUnknownProductChangesNothing() throws SQLException {
        IllegalStateException e = assertThrows(IllegalStateException.class, () -> TransactionDrills.moveStock(db, "Ghost", "Rice 25kg", 1));
        assertEquals("Unknown product", e.getMessage());
        assertEquals(17, committedQuantity("Rice 25kg"));
    }

    @Test
    void movingAllTheStockIsAllowed() throws SQLException {
        TransactionDrills.moveStock(db, "Rice 1kg bag", "Rice 25kg", 3);
        assertEquals(0, committedQuantity("Rice 1kg bag"));
        assertEquals(20, committedQuantity("Rice 25kg"));
    }
}
