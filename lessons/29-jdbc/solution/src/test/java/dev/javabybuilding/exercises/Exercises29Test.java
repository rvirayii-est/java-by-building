package dev.javabybuilding.exercises;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

class Exercises29Test {

    private Connection db;

    @BeforeEach
    void openDatabase() throws SQLException {
        db = DriverManager.getConnection("jdbc:h2:mem:l29-" + UUID.randomUUID());
        try (Statement statement = db.createStatement()) {
            statement.execute("CREATE TABLE product (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60) NOT NULL UNIQUE,"
                    + " price DECIMAL(10,2) NOT NULL, reorder_level INT NOT NULL, quantity INT NOT NULL)");
            statement.execute("INSERT INTO product (name, price, reorder_level, quantity) VALUES"
                    + " ('Rice 25kg', 1250.50, 10, 17), ('Cooking Oil 1L', 98.00, 10, 12), ('Sugar 1kg', 75.00, 10, 4)");
        }
    }

    @AfterEach
    void closeDatabase() throws SQLException {
        db.close();
    }

    @Test
    void countProductsCountsRows() throws SQLException {
        assertEquals(3, JdbcDrills.countProducts(db));
    }

    @Test
    void priceOfFindsAProduct() throws SQLException {
        assertEquals(new BigDecimal("98.00"), JdbcDrills.priceOf(db, "Cooking Oil 1L").orElseThrow());
    }

    @Test
    void priceOfAnUnknownProductIsEmpty() throws SQLException {
        assertTrue(JdbcDrills.priceOf(db, "Salt").isEmpty());
    }

    @Test
    void priceOfIsNotFooledByTextThatLooksLikeSql() throws SQLException {
        assertTrue(JdbcDrills.priceOf(db, "x' OR '1'='1").isEmpty());
        assertEquals(3, JdbcDrills.countProducts(db));
    }

    @Test
    void addProductStoresNameAndPriceWithZeroStock() throws SQLException {
        JdbcDrills.addProduct(db, "Coffee Sachet", new BigDecimal("8.50"));
        assertEquals(4, JdbcDrills.countProducts(db));
        assertEquals(new BigDecimal("8.50"), JdbcDrills.priceOf(db, "Coffee Sachet").orElseThrow());
        assertEquals(0, JdbcDrills.stockByName(db).get("Coffee Sachet"));
    }

    @Test
    void addProductWorksForANameWithAnApostrophe() throws SQLException {
        JdbcDrills.addProduct(db, "Nestle's Milo", new BigDecimal("12.00"));
        assertEquals(new BigDecimal("12.00"), JdbcDrills.priceOf(db, "Nestle's Milo").orElseThrow());
    }

    @Test
    void addProductCannotBeUsedToRunExtraSql() throws SQLException {
        JdbcDrills.addProduct(db, "x'); DELETE FROM product; --", new BigDecimal("1.00"));
        assertEquals(4, JdbcDrills.countProducts(db));
    }

    @Test
    void namesCheaperThanAreSorted() throws SQLException {
        assertEquals(List.of("Cooking Oil 1L", "Sugar 1kg"), JdbcDrills.namesCheaperThan(db, new BigDecimal("100.00")));
        assertEquals(List.of(), JdbcDrills.namesCheaperThan(db, new BigDecimal("10.00")));
    }

    @Test
    void receiveAddsToTheQuantityAndSaysHowManyRowsChanged() throws SQLException {
        assertEquals(1, JdbcDrills.receive(db, "Sugar 1kg", 20));
        assertEquals(24, JdbcDrills.stockByName(db).get("Sugar 1kg"));
    }

    @Test
    void receiveOnAnUnknownProductChangesNothing() throws SQLException {
        assertEquals(0, JdbcDrills.receive(db, "Salt", 5));
    }

    @Test
    void stockByNameKeepsTheOrderOfTheIds() throws SQLException {
        Map<String, Integer> stock = JdbcDrills.stockByName(db);
        assertEquals(List.of("Rice 25kg", "Cooking Oil 1L", "Sugar 1kg"), List.copyOf(stock.keySet()));
        assertEquals(List.of(17, 12, 4), List.copyOf(stock.values()));
    }
}
