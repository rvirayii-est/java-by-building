// Run with:  java -cp <path to the H2 jar> lessons/29-jdbc/examples/JdbcTour.java   (from the repository root)
// The five JDBC moves, in order: connect, run a statement, fill the ? holes, read the rows, close everything.
// Then the reason PreparedStatement exists: the same attack against two ways of asking for a product.
import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

public class JdbcTour {

    public static void main(String[] args) throws SQLException {
        // 1. CONNECT. The URL says which database: jdbc:h2:mem:NAME is H2, kept in memory. try-with-resources closes the connection.
        try (Connection db = DriverManager.getConnection("jdbc:h2:mem:jdbc-tour")) {
            System.out.println("1. Connected to " + db.getMetaData().getDatabaseProductName() + " " + db.getMetaData().getDatabaseProductVersion());

            // 2. RUN a statement with no values: a plain Statement is fine.
            try (Statement statement = db.createStatement()) {
                statement.execute("CREATE TABLE product (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60) NOT NULL UNIQUE, "
                        + "price DECIMAL(10,2) NOT NULL, quantity INT NOT NULL)");
            }
            System.out.println("2. Table created");

            // 3. FILL the ? holes of a PreparedStatement. The numbers start at 1. The values travel apart from the SQL.
            String insert = "INSERT INTO product (name, price, quantity) VALUES (?, ?, ?)";
            try (PreparedStatement statement = db.prepareStatement(insert)) {
                add(statement, "Rice 25kg", "1250.50", 17);
                add(statement, "Cooking Oil 1L", "98.00", 12);
                add(statement, "Nestle's Milo", "12.00", 40); // an apostrophe is no problem when the value is passed separately
            }
            System.out.println("3. Three rows inserted");

            // 4. READ rows: executeQuery gives a ResultSet; next() moves to the next row; get...("column") reads a value.
            System.out.println("4. Products cheaper than 100.00:");
            try (PreparedStatement statement = db.prepareStatement("SELECT name, price, quantity FROM product WHERE price < ? ORDER BY name")) {
                statement.setBigDecimal(1, new BigDecimal("100.00"));
                try (ResultSet rows = statement.executeQuery()) {
                    while (rows.next()) {
                        System.out.printf("   %-15s %8s  %3d in stock%n", rows.getString("name"), rows.getBigDecimal("price").toPlainString(), rows.getInt("quantity"));
                    }
                }
            }

            // UPDATE and DELETE use executeUpdate, which returns how many rows changed.
            try (PreparedStatement statement = db.prepareStatement("UPDATE product SET quantity = quantity + ? WHERE name = ?")) {
                statement.setInt(1, 10);
                statement.setString(2, "Rice 25kg");
                System.out.println("   Rows updated: " + statement.executeUpdate());
                statement.setString(2, "Salt");
                System.out.println("   Rows updated for an unknown product: " + statement.executeUpdate());
            }

            // 5. CLOSE: nothing to write. Every try-with-resources above closed its Statement, ResultSet and, at the end, the Connection.

            System.out.println("\n== SQL injection: a visitor types this as the product name:");
            String typed = "nothing' OR '1'='1";
            System.out.println("   " + typed);

            String glued = "SELECT COUNT(*) FROM product WHERE name = '" + typed + "'";
            System.out.println("\nThe WRONG way, gluing text into SQL:\n   " + glued);
            System.out.println("   -> " + count(db.prepareStatement(glued)) + " rows found (every product! the quote changed the meaning of the SQL)");

            PreparedStatement safe = db.prepareStatement("SELECT COUNT(*) FROM product WHERE name = ?");
            safe.setString(1, typed);
            System.out.println("\nThe RIGHT way, a ? hole filled with the same text:\n   SELECT COUNT(*) FROM product WHERE name = ?");
            System.out.println("   -> " + count(safe) + " rows found (the whole text is just a name nobody has)");
            safe.close();
        }
    }

    static void add(PreparedStatement statement, String name, String price, int quantity) throws SQLException {
        statement.setString(1, name);
        statement.setBigDecimal(2, new BigDecimal(price));
        statement.setInt(3, quantity);
        statement.executeUpdate();
    }

    static int count(PreparedStatement statement) throws SQLException {
        try (statement; ResultSet rows = statement.executeQuery()) {
            rows.next();
            return rows.getInt(1);
        }
    }
}
