-- TODO 1: product: UNIQUE name, name not blank, price 0.01..10000.00, reorder_level >= 0, quantity >= 0, defaults.
CREATE TABLE product (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(60)   NOT NULL,
    price         DECIMAL(10,2) NOT NULL,
    reorder_level INT           NOT NULL,
    quantity      INT           NOT NULL
);

-- TODO 2: customer: UNIQUE (name, phone) and a name that is not blank.
CREATE TABLE customer (
    id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(60) NOT NULL,
    phone VARCHAR(20) NOT NULL
);

-- TODO 3: sale: named foreign key to customer with ON DELETE SET NULL; payment CHECK; discount DEFAULT 'none'.
CREATE TABLE sale (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INT REFERENCES customer (id),
    sold_at     TIMESTAMP   NOT NULL,
    discount    VARCHAR(20) NOT NULL,
    payment     VARCHAR(10) NOT NULL
);

-- TODO 4: sale_line: named foreign keys (sale: ON DELETE CASCADE, product: default), CHECKs on unit_price and quantity.
CREATE TABLE sale_line (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id    INT           NOT NULL REFERENCES sale (id),
    product_id INT           NOT NULL REFERENCES product (id),
    unit_price DECIMAL(10,2) NOT NULL,
    quantity   INT           NOT NULL
);

-- TODO 5: stock_movement: named foreign key to product, CHECKs on type and quantity.
CREATE TABLE stock_movement (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INT         NOT NULL REFERENCES product (id),
    type       VARCHAR(10) NOT NULL,
    quantity   INT         NOT NULL,
    moved_at   TIMESTAMP   NOT NULL
);

