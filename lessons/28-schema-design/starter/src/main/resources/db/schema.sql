--   * deleting a customer must keep their sales (ON DELETE SET NULL); deleting a sale must delete its lines (ON DELETE CASCADE);
--     a product with sales must NOT be deletable (the default)
--   * reorder_level and quantity default to 0, discount defaults to 'none'
--   * four indexes: idx_sale_line_sale (sale_line.sale_id), idx_sale_line_product (sale_line.product_id),
