-- The shop's database, designed for real use (lesson 28). Lessons 29-31 create these tables; lesson 32 turns this
-- file into the first versioned migration.
--
-- Design rules used here:
--   * table names are singular and in lower case with underscores (sale_line); every table has an id primary key;
--   * a foreign key column is called <table>_id and always gets a constraint (so the database keeps the links true);
--   * a rule the business has (a price is 0.01 to 10,000.00) is a CHECK constraint, because the database is the last
--     line of defence: a bug, a spreadsheet import or a second program cannot get bad rows past it;
--   * every constraint has a name, so an error message says WHICH rule was broken.

CREATE TABLE product (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(60)   NOT NULL,
    price         DECIMAL(10,2) NOT NULL,
    reorder_level INT           NOT NULL DEFAULT 0,
    quantity      INT           NOT NULL DEFAULT 0,
    CONSTRAINT uq_product_name     UNIQUE (name),
    CONSTRAINT ck_product_name     CHECK (TRIM(name) <> ''),
    CONSTRAINT ck_product_price    CHECK (price >= 0.01 AND price <= 10000.00),
    CONSTRAINT ck_product_reorder  CHECK (reorder_level >= 0),
    CONSTRAINT ck_product_quantity CHECK (quantity >= 0)
);

CREATE TABLE customer (
    id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(60) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    CONSTRAINT uq_customer_person UNIQUE (name, phone),
    CONSTRAINT ck_customer_name   CHECK (TRIM(name) <> '')
);

-- customer_id is empty (NULL) for a walk-in. If a customer row is ever deleted, their sales stay (SET NULL):
-- the shop's income must not vanish because a contact was removed.
CREATE TABLE sale (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INT,
    sold_at     TIMESTAMP   NOT NULL,
    discount    VARCHAR(20) NOT NULL DEFAULT 'none',
    payment     VARCHAR(10) NOT NULL,
    CONSTRAINT fk_sale_customer FOREIGN KEY (customer_id) REFERENCES customer (id) ON DELETE SET NULL,
    CONSTRAINT ck_sale_payment  CHECK (payment IN ('CASH', 'GCASH', 'CARD'))
);

-- A line cannot live without its sale (CASCADE: delete the sale, its lines go too). A line DOES block deleting a
-- product (the default, RESTRICT): history must not point at a product that no longer exists.
-- unit_price is a deliberate copy of the price at the time of the sale.
CREATE TABLE sale_line (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id    INT           NOT NULL,
    product_id INT           NOT NULL,
    unit_price DECIMAL(10,2) NOT NULL,
    quantity   INT           NOT NULL,
    CONSTRAINT fk_sale_line_sale    FOREIGN KEY (sale_id)    REFERENCES sale (id) ON DELETE CASCADE,
    CONSTRAINT fk_sale_line_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_sale_line_price    CHECK (unit_price >= 0.01 AND unit_price <= 10000.00),
    CONSTRAINT ck_sale_line_quantity CHECK (quantity > 0)
);

CREATE TABLE stock_movement (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INT         NOT NULL,
    type       VARCHAR(10) NOT NULL,
    quantity   INT         NOT NULL,
    moved_at   TIMESTAMP   NOT NULL,
    CONSTRAINT fk_movement_product  FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_movement_type     CHECK (type IN ('RECEIVED', 'SOLD')),
    CONSTRAINT ck_movement_quantity CHECK (quantity > 0)
);

-- Indexes: a sorted side-list that lets the database find rows without reading the whole table. The primary key and
-- the unique constraints already have one. Add one where you search, join or sort a lot.
CREATE INDEX idx_sale_line_sale    ON sale_line (sale_id);
CREATE INDEX idx_sale_line_product ON sale_line (product_id);
CREATE INDEX idx_sale_sold_at      ON sale (sold_at);
CREATE INDEX idx_movement_product  ON stock_movement (product_id, moved_at);
