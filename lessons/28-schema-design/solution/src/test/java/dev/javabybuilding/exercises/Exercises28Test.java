package dev.javabybuilding.exercises;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

class Exercises28Test {

    private Connection db;

    @BeforeEach
    void openDatabase() throws SQLException {
        db = DriverManager.getConnection("jdbc:h2:mem:l28-" + UUID.randomUUID());
        run("CREATE TABLE product (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60) NOT NULL, price DECIMAL(10,2) NOT NULL)");
        run("INSERT INTO product (name, price) VALUES ('Rice 25kg', 1250.50), ('Sugar 1kg', 75.00)");
    }

    @AfterEach
    void closeDatabase() throws SQLException {
        db.close();
    }

    private void run(String sql) throws SQLException {
        try (Statement statement = db.createStatement()) {
            statement.execute(sql);
        }
    }

    private String one(String sql) throws SQLException {
        try (Statement statement = db.createStatement(); ResultSet rows = statement.executeQuery(sql)) {
            rows.next();
            return rows.getString(1);
        }
    }

    /** Runs the SQL, expects a refusal, and returns the message in capitals (so the rule names are easy to find). */
    private String refused(String sql) {
        return assertThrows(SQLException.class, () -> run(sql)).getMessage().toUpperCase();
    }

    private void buildSupplierSide() throws SQLException {
        run(SchemaDrills.createSupplier());
        run(SchemaDrills.linkProductToSupplier());
        run(SchemaDrills.createDelivery());
        run(SchemaDrills.indexDeliveryDate());
        run("INSERT INTO supplier (name) VALUES ('Metro Trading'), ('Gold Star')");
    }

    // ---- createSupplier

    @Test
    void aSupplierNameIsRequiredUniqueAndNotBlank() throws SQLException {
        run(SchemaDrills.createSupplier());
        run("INSERT INTO supplier (name, phone) VALUES ('Metro Trading', NULL)");
        assertTrue(refused("INSERT INTO supplier (name) VALUES ('Metro Trading')").contains("UQ_SUPPLIER_NAME"));
        assertTrue(refused("INSERT INTO supplier (name) VALUES ('   ')").contains("CK_SUPPLIER_NAME"));
        refused("INSERT INTO supplier (phone) VALUES ('0917')");
        assertEquals("1", one("SELECT COUNT(*) FROM supplier"));
    }

    // ---- linkProductToSupplier

    @Test
    void aProductMayHaveASupplierOrNone() throws SQLException {
        buildSupplierSide();
        run("UPDATE product SET supplier_id = 1 WHERE name = 'Rice 25kg'");
        assertEquals("1", one("SELECT COUNT(*) FROM product WHERE supplier_id IS NULL"));
        refused("UPDATE product SET supplier_id = 99 WHERE name = 'Rice 25kg'");
    }

    @Test
    void deletingASupplierKeepsItsProducts() throws SQLException {
        buildSupplierSide();
        run("UPDATE product SET supplier_id = 2");
        run("DELETE FROM supplier WHERE name = 'Gold Star'");
        assertEquals("2", one("SELECT COUNT(*) FROM product"));
        assertEquals("2", one("SELECT COUNT(*) FROM product WHERE supplier_id IS NULL"));
    }

    // ---- createDelivery

    @Test
    void aDeliveryNeedsAPositiveQuantity() throws SQLException {
        buildSupplierSide();
        run("INSERT INTO delivery (supplier_id, product_id, quantity, received_at) VALUES (1, 1, 20, TIMESTAMP '2026-03-01 08:00:00')");
        assertTrue(refused("INSERT INTO delivery (supplier_id, product_id, quantity, received_at) VALUES (1, 1, 0, TIMESTAMP '2026-03-01 08:00:00')")
                .contains("CK_DELIVERY_QUANTITY"));
        assertEquals("1", one("SELECT COUNT(*) FROM delivery"));
    }

    @Test
    void aDeliveryNeedsARealSupplierAndProduct() throws SQLException {
        buildSupplierSide();
        assertTrue(refused("INSERT INTO delivery (supplier_id, product_id, quantity, received_at) VALUES (99, 1, 5, TIMESTAMP '2026-03-01 08:00:00')")
                .contains("FK_DELIVERY_SUPPLIER"));
        assertTrue(refused("INSERT INTO delivery (supplier_id, product_id, quantity, received_at) VALUES (1, 99, 5, TIMESTAMP '2026-03-01 08:00:00')")
                .contains("FK_DELIVERY_PRODUCT"));
        refused("INSERT INTO delivery (product_id, quantity, received_at) VALUES (1, 5, TIMESTAMP '2026-03-01 08:00:00')");
    }

    @Test
    void aSupplierOrProductWithDeliveriesCannotBeDeleted() throws SQLException {
        buildSupplierSide();
        run("INSERT INTO delivery (supplier_id, product_id, quantity, received_at) VALUES (1, 1, 20, TIMESTAMP '2026-03-01 08:00:00')");
        assertTrue(refused("DELETE FROM supplier WHERE id = 1").contains("FK_DELIVERY_SUPPLIER"));
        assertTrue(refused("DELETE FROM product WHERE id = 1").contains("FK_DELIVERY_PRODUCT"));
    }

    // ---- indexDeliveryDate

    @Test
    void theDeliveryDateIndexExists() throws SQLException {
        buildSupplierSide();
        assertEquals("1", one("SELECT COUNT(DISTINCT index_name) FROM information_schema.indexes WHERE LOWER(index_name) = 'idx_delivery_received_at'"));
    }
}
