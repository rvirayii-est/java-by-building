package dev.javabybuilding.exercises;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Lesson 25 drills: think in tables, keys and links. The first two drills answer with SQL text (the tests run your
 * SQL on a real in-memory database); the third finds the problem a flat sheet has.
 */
public class ErdDrills {

    /**
     * A new table for the shop's suppliers: an id that the database numbers by itself and that is the primary key,
     * a name (required, up to 60 characters) and a phone (optional, up to 20 characters).
     */
    public static String createSupplierTable() {
        return "CREATE TABLE supplier ("
                + " id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + " name VARCHAR(60) NOT NULL,"
                + " phone VARCHAR(20))";
    }

    /**
     * One supplier supplies many products, so the link is a column in product (the "many" side): supplier_id, whole
     * number, may be empty, and a foreign key to supplier (id).
     */
    public static String linkProductToSupplier() {
        return "ALTER TABLE product ADD COLUMN supplier_id INT REFERENCES supplier (id)";
    }

    /**
     * A flat sheet repeats the customer on every row. Each row is {customer, phone}. Return the customers (each once,
     * in the order they first appear) who have MORE THAN ONE different phone number: the sheet disagrees with itself.
     */
    public static List<String> customersWithConflictingPhones(List<String[]> rows) {
        Map<String, Set<String>> phonesByCustomer = new LinkedHashMap<>();
        for (String[] row : rows) {
            phonesByCustomer.computeIfAbsent(row[0], name -> new LinkedHashSet<>()).add(row[1]);
        }
        List<String> conflicting = new ArrayList<>();
        phonesByCustomer.forEach((name, phones) -> {
            if (phones.size() > 1) {
                conflicting.add(name);
            }
        });
        return conflicting;
    }
}
