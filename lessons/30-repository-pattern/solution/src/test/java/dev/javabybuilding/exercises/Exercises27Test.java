package dev.javabybuilding.exercises;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

class Exercises27Test {

    private Connection db;

    @BeforeEach
    void openDatabase() throws SQLException {
        db = DriverManager.getConnection("jdbc:h2:mem:l27-" + UUID.randomUUID());
        run("CREATE TABLE product (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60) NOT NULL, price DECIMAL(10,2) NOT NULL)");
        run("CREATE TABLE customer (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60) NOT NULL, phone VARCHAR(20) NOT NULL)");
        run("CREATE TABLE sale (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id INT REFERENCES customer (id), sold_at TIMESTAMP NOT NULL)");
        run("CREATE TABLE sale_line (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sale_id INT NOT NULL REFERENCES sale (id),"
                + " product_id INT NOT NULL REFERENCES product (id), unit_price DECIMAL(10,2) NOT NULL, quantity INT NOT NULL)");
        run("INSERT INTO product (name, price) VALUES ('Rice 25kg', 1250.50), ('Cooking Oil 1L', 98.00), ('Sugar 1kg', 75.00),"
                + " ('Sardines 155g', 24.00), ('Soy Sauce 500ml', 38.00), ('Instant Noodles', 14.00)");
        run("INSERT INTO customer (name, phone) VALUES ('Ana Reyes', '0917'), ('Ben Santos', '0918'), ('Carla Dizon', '0919')");
        run("INSERT INTO sale (customer_id, sold_at) VALUES (1, TIMESTAMP '2026-03-01 09:30:00'), (NULL, TIMESTAMP '2026-03-01 10:15:00'),"
                + " (2, TIMESTAMP '2026-03-02 14:05:00'), (1, TIMESTAMP '2026-03-02 16:40:00'), (NULL, TIMESTAMP '2026-03-03 09:10:00')");
        run("INSERT INTO sale_line (sale_id, product_id, unit_price, quantity) VALUES (1, 1, 1250.50, 2), (2, 4, 24.00, 6), (2, 6, 14.00, 10),"
                + " (3, 2, 98.00, 3), (3, 3, 75.00, 4), (4, 1, 1250.50, 1), (4, 4, 24.00, 4), (5, 6, 14.00, 25)");
    }

    @AfterEach
    void closeDatabase() throws SQLException {
        db.close();
    }

    private void run(String sql) throws SQLException {
        try (Statement statement = db.createStatement()) {
            statement.execute(sql);
        }
    }

    /** Header line (column names), then one line per row, cells joined with " | ". */
    private List<String> table(String sql) throws SQLException {
        List<String> lines = new ArrayList<>();
        try (Statement statement = db.createStatement(); ResultSet rs = statement.executeQuery(sql)) {
            ResultSetMetaData meta = rs.getMetaData();
            List<String> names = new ArrayList<>();
            for (int c = 1; c <= meta.getColumnCount(); c++) {
                names.add(meta.getColumnLabel(c).toLowerCase());
            }
            lines.add(String.join(" | ", names));
            while (rs.next()) {
                List<String> cells = new ArrayList<>();
                for (int c = 1; c <= meta.getColumnCount(); c++) {
                    cells.add(rs.getString(c));
                }
                lines.add(String.join(" | ", cells));
            }
        }
        return lines;
    }

    @Test
    void customerSalesSkipsTheWalkIns() throws SQLException {
        assertEquals(List.of("customer | sale_id", "Ana Reyes | 1", "Ben Santos | 3", "Ana Reyes | 4"), table(JoinDrills.customerSales()));
    }

    @Test
    void allSalesWithWalkInsKeepsEverySale() throws SQLException {
        assertEquals(List.of("sale_id | customer", "1 | Ana Reyes", "2 | Walk-in", "3 | Ben Santos", "4 | Ana Reyes", "5 | Walk-in"),
                table(JoinDrills.allSalesWithWalkIns()));
    }

    @Test
    void unitsPerProductCountsOnlyProductsThatSold() throws SQLException {
        assertEquals(List.of("product | units", "Instant Noodles | 35", "Sardines 155g | 10", "Sugar 1kg | 4", "Cooking Oil 1L | 3", "Rice 25kg | 3"),
                table(JoinDrills.unitsPerProduct()));
    }

    @Test
    void productsNeverSoldFindsTheSoySauce() throws SQLException {
        assertEquals(List.of("product", "Soy Sauce 500ml"), table(JoinDrills.productsNeverSold()));
    }

    @Test
    void aProductBecomesSoldWhenASaleLineMentionsIt() throws SQLException {
        run("INSERT INTO sale_line (sale_id, product_id, unit_price, quantity) VALUES (5, 5, 38.00, 1)");
        assertEquals(List.of("product"), table(JoinDrills.productsNeverSold()));
    }

    @Test
    void bigSpendersNeedAtLeast1000Pesos() throws SQLException {
        assertEquals(List.of("customer | spent", "Ana Reyes | 3847.50"), table(JoinDrills.bigSpenders()));
    }

    @Test
    void salesPerDayCountsSalesNotLines() throws SQLException {
        assertEquals(List.of("sale_day | sales", "2026-03-01 | 2", "2026-03-02 | 2", "2026-03-03 | 1"), table(JoinDrills.salesPerDay()));
    }
}
