package dev.javabybuilding.exercises;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

class Exercises25Test {

    private Connection db;

    @BeforeEach
    void openDatabase() throws SQLException {
        db = DriverManager.getConnection("jdbc:h2:mem:l25-" + UUID.randomUUID()); // its own database, gone when closed
        run("CREATE TABLE product (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60) NOT NULL)");
    }

    @AfterEach
    void closeDatabase() throws SQLException {
        db.close();
    }

    private void run(String sql) throws SQLException {
        try (Statement statement = db.createStatement()) {
            statement.execute(sql);
        }
    }

    private int count(String sql) throws SQLException {
        try (Statement statement = db.createStatement(); ResultSet rows = statement.executeQuery(sql)) {
            rows.next();
            return rows.getInt(1);
        }
    }

    // ---- createSupplierTable

    @Test
    void theSupplierTableCanBeCreated() throws SQLException {
        run(ErdDrills.createSupplierTable());
        run("INSERT INTO supplier (name) VALUES ('Metro Trading')");
        assertEquals(1, count("SELECT COUNT(*) FROM supplier"));
    }

    @Test
    void theSupplierIdIsNumberedByTheDatabase() throws SQLException {
        run(ErdDrills.createSupplierTable());
        run("INSERT INTO supplier (name) VALUES ('Metro Trading'), ('Gold Star')");
        assertEquals(2, count("SELECT MAX(id) FROM supplier"));
    }

    @Test
    void aSupplierNeedsAName() throws SQLException {
        run(ErdDrills.createSupplierTable());
        assertThrows(SQLException.class, () -> run("INSERT INTO supplier (phone) VALUES ('0917')"));
    }

    @Test
    void aSupplierCanHaveNoPhone() throws SQLException {
        run(ErdDrills.createSupplierTable());
        run("INSERT INTO supplier (name, phone) VALUES ('Gold Star', NULL)");
        assertEquals(1, count("SELECT COUNT(*) FROM supplier WHERE phone IS NULL"));
    }

    // ---- linkProductToSupplier

    @Test
    void aProductCanPointAtAnExistingSupplier() throws SQLException {
        run(ErdDrills.createSupplierTable());
        run(ErdDrills.linkProductToSupplier());
        run("INSERT INTO supplier (name) VALUES ('Metro Trading')");
        run("INSERT INTO product (name, supplier_id) VALUES ('Rice 25kg', 1)");
        assertEquals(1, count("SELECT COUNT(*) FROM product WHERE supplier_id = 1"));
    }

    @Test
    void aProductMayHaveNoSupplier() throws SQLException {
        run(ErdDrills.createSupplierTable());
        run(ErdDrills.linkProductToSupplier());
        run("INSERT INTO product (name) VALUES ('Sugar 1kg')");
        assertEquals(1, count("SELECT COUNT(*) FROM product WHERE supplier_id IS NULL"));
    }

    @Test
    void aProductCannotPointAtASupplierThatDoesNotExist() throws SQLException {
        run(ErdDrills.createSupplierTable());
        run(ErdDrills.linkProductToSupplier());
        assertThrows(SQLException.class, () -> run("INSERT INTO product (name, supplier_id) VALUES ('Rice 25kg', 99)"));
    }

    // ---- customersWithConflictingPhones

    @Test
    void aCustomerWithTwoPhonesIsReported() {
        List<String[]> rows = List.of(
                new String[] {"Ana Reyes", "0917 123 4567"},
                new String[] {"Ben Santos", "0918 987 6543"},
                new String[] {"Ana Reyes", "0999 000 1111"});
        assertEquals(List.of("Ana Reyes"), ErdDrills.customersWithConflictingPhones(rows));
    }

    @Test
    void theSamePhoneRepeatedIsNotAConflict() {
        List<String[]> rows = List.of(
                new String[] {"Ana Reyes", "0917 123 4567"},
                new String[] {"Ana Reyes", "0917 123 4567"});
        assertTrue(ErdDrills.customersWithConflictingPhones(rows).isEmpty());
    }

    @Test
    void eachConflictingCustomerIsListedOnceInOrderOfFirstAppearance() {
        List<String[]> rows = List.of(
                new String[] {"Ben Santos", "1"},
                new String[] {"Ana Reyes", "2"},
                new String[] {"Ben Santos", "3"},
                new String[] {"Ana Reyes", "4"},
                new String[] {"Ben Santos", "5"});
        assertEquals(List.of("Ben Santos", "Ana Reyes"), ErdDrills.customersWithConflictingPhones(rows));
    }

    @Test
    void anEmptySheetHasNoConflicts() {
        assertTrue(ErdDrills.customersWithConflictingPhones(List.of()).isEmpty());
    }
}
