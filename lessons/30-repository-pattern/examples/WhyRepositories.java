// Run with:  java -cp <path to the H2 jar> lessons/30-repository-pattern/examples/WhyRepositories.java   (from the repository root)
// One interface, three places to keep the data (memory, a file, an H2 database). The same "business" code and the same
// checks run on all three. This is the repository pattern in 120 lines.
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

public class WhyRepositories {

    /** What the shop needs from "somewhere to keep notes". It says nothing about HOW. */
    interface NoteRepository {
        void add(String text);
        List<String> findAll();
    }

    /** The business code. It only knows the interface, so it works with every storage below. */
    static class ShopDiary {
        private final NoteRepository notes;

        ShopDiary(NoteRepository notes) {
            this.notes = notes;
        }

        String record(String text) {
            if (text.isBlank()) {
                return "refused: empty note";
            }
            notes.add(text.strip());
            return "saved (" + notes.findAll().size() + " notes)";
        }
    }

    static class InMemoryNotes implements NoteRepository {
        private final List<String> list = new ArrayList<>();
        public void add(String text) { list.add(text); }
        public List<String> findAll() { return List.copyOf(list); }
    }

    static class FileNotes implements NoteRepository {
        private final Path file;
        FileNotes(Path file) { this.file = file; }
        public void add(String text) {
            try {
                Files.writeString(file, text + "\n", java.nio.file.StandardOpenOption.CREATE, java.nio.file.StandardOpenOption.APPEND);
            } catch (IOException e) {
                throw new IllegalStateException(e);
            }
        }
        public List<String> findAll() {
            try {
                return Files.exists(file) ? Files.readAllLines(file) : List.of();
            } catch (IOException e) {
                throw new IllegalStateException(e);
            }
        }
    }

    static class JdbcNotes implements NoteRepository {
        private final Connection db;
        JdbcNotes(Connection db) throws SQLException {
            this.db = db;
            db.createStatement().execute("CREATE TABLE note (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, text VARCHAR(200) NOT NULL)");
        }
        public void add(String text) {
            try (PreparedStatement statement = db.prepareStatement("INSERT INTO note (text) VALUES (?)")) {
                statement.setString(1, text);
                statement.executeUpdate();
            } catch (SQLException e) {
                throw new IllegalStateException(e);
            }
        }
        public List<String> findAll() {
            try (PreparedStatement statement = db.prepareStatement("SELECT text FROM note ORDER BY id"); ResultSet rows = statement.executeQuery()) {
                List<String> notes = new ArrayList<>();
                while (rows.next()) {
                    notes.add(rows.getString("text"));
                }
                return notes;
            } catch (SQLException e) {
                throw new IllegalStateException(e);
            }
        }
    }

    public static void main(String[] args) throws Exception {
        Path folder = Files.createTempDirectory("diary");
        try (Connection db = DriverManager.getConnection("jdbc:h2:mem:why-repositories")) {
            Map<String, NoteRepository> stores = new LinkedHashMap<>();
            stores.put("memory", new InMemoryNotes());
            stores.put("file  ", new FileNotes(folder.resolve("notes.txt")));
            stores.put("H2 db ", new JdbcNotes(db));

            for (Map.Entry<String, NoteRepository> store : stores.entrySet()) {
                ShopDiary diary = new ShopDiary(store.getValue());
                System.out.println("[" + store.getKey() + "] " + diary.record("Rice delivery arrived")
                        + " | " + diary.record("   ")
                        + " | " + diary.record("Nestle's Milo is out") + " -> " + store.getValue().findAll());
            }
        } finally {
            try (var files = Files.list(folder)) {
                for (Path f : (Iterable<Path>) files::iterator) {
                    Files.delete(f);
                }
            }
            Files.delete(folder);
        }
    }
}
